def safe_copy(src: Path, dst: Path) -> None:
    """Kopieert een bestand. Probeert metadata te behouden (copy2), maar valt terug op copyfile bij OS-fouten (zoals op netwerkshares)."""
    try:
        shutil.copy2(src, dst)
    except OSError:
        shutil.copyfile(src, dst)

def is_file_writable(path: Path) -> bool:
    """Controleert of een bestand herschrijfbaar is (niet ReadOnly / schrijfbeveiligd)."""
    if path.exists():
        if not os.access(path, os.W_OK):
            return False
        try:
            with open(path, "a", encoding="utf-8"):
                pass
            return True
        except (PermissionError, OSError):
            return False
    else:
        # Als het bestand nog niet bestaat, controleer of de bovenliggende map beschrijfbaar is
        parent = path.parent
        while not parent.exists() and parent != parent.parent:
            parent = parent.parent
        return os.access(parent, os.W_OK)



