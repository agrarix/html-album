# Thumbnail maken met Pillow (bijgesneden vulling)
# ---------------------------------------------------------------------------
def make_thumbnail(src: Path, dst: Path) -> None:
    if not HAS_PIL:
        try:
            safe_copy(src, dst)
        except Exception as e:
            log_bericht(f"    ⚠  Could not copy file as thumbnail fallback: {e}")
        return
    try:
        with safe_image_open(src) as img:
            img = ImageOps.exif_transpose(img)
            img = img.convert("RGB")
            img.thumbnail(THUMB_SIZE, Image.LANCZOS)
            
            if WATERMARK and WM_ICON_SIZE > 0:
                img = apply_watermark(img, WM_ICON_SIZE)
                
            img.save(dst, "JPEG", quality=85, optimize=True)
    except PermissionError as pe:
        log_bericht(f"    ⚠  Access denied (file in use) while creating thumbnail for '{src.name}': {pe}")
    except Exception as exc:
        log_bericht(f"    ⚠  Thumbnail generation failed for '{src.name}': {exc}")
        try:
            safe_copy(src, dst)
        except Exception:
            pass

