def apply_watermark(img: "Image.Image", font_size: int) -> "Image.Image":
    """Voegt een semi-transparant watermerk toe aan de afbeelding met de opgegeven lettergrootte."""
    if not HAS_PIL or not WATERMARK or font_size <= 0:
        return img
        
    try:
        from PIL import ImageDraw, ImageFont
    except ImportError:
        return img

    try:
        # Maak een RGBA-laag voor het watermerk
        watermark_layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        draw = ImageDraw.Draw(watermark_layer)
        
        # Probeer het geconfigureerde font te laden
        font = None
        font_paths = [
            WM_FONT,
            f"{WM_FONT}.ttf",
            f"{WM_FONT}.TTF",
        ]
        
        if sys.platform == "win32":
            font_paths.extend([
                f"C:\\Windows\\Fonts\\{WM_FONT}.ttf",
                f"C:\\Windows\\Fonts\\{WM_FONT}.TTF",
                f"C:\\Windows\\Fonts\\{WM_FONT}bd.ttf",
                "C:\\Windows\\Fonts\\arial.ttf",
            ])
        else:
            font_paths.extend([
                f"/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                f"/usr/share/fonts/truetype/freefont/FreeSans.ttf",
                f"/usr/share/fonts/truetype/msttcorefonts/{WM_FONT}.ttf",
                f"/usr/share/fonts/truetype/msttcorefonts/{WM_FONT}.TTF",
            ])
            
        for path in font_paths:
            try:
                font = ImageFont.truetype(path, font_size)
                break
            except Exception:
                continue
                
        if font is None:
            font = ImageFont.load_default()
            
        # Bereken tekstafmetingen
        try:
            left, top, right, bottom = draw.textbbox((0, 0), WATERMARK, font=font)
            text_width = right - left
            text_height = bottom - top
        except AttributeError:
            text_width, text_height = draw.textsize(WATERMARK, font=font)
            
        # Bereken X op basis van uitlijning (left, center, right)
        if WM_ALLIGNMENT == "left":
            x = 20
        elif WM_ALLIGNMENT == "right":
            x = img.width - text_width - 20
        else:  # center
            x = (img.width - text_width) // 2
            
        y = int(img.height * WM_LOCATION / 100) - (text_height // 2)
        
        x = max(0, min(x, img.width - text_width))
        y = max(0, min(y, img.height - text_height))
        
        opacity = 1.0 - WM_TRANSPARANCY
        alpha = int(255 * max(0.0, min(1.0, opacity)))
        
        color = (255, 255, 255, alpha)
        draw.text((x, y), WATERMARK, font=font, fill=color)
        
        img_rgba = img.convert("RGBA")
        combined = Image.alpha_composite(img_rgba, watermark_layer)
        return combined.convert("RGB")
    except Exception as e:
        log_bericht(f"    ⚠  Fout bij toepassen watermerk: {e}")
        return img

def convert_heic_to_jpeg(src_path: Path, dst_path: Path) -> None:
    """Converteert een HEIC/HEIF afbeelding naar JPEG met behoud van EXIF-metadata."""
    if HAS_HEIF:
        with safe_image_open(src_path) as im:
            im = ImageOps.exif_transpose(im)
            exif_bytes = im.info.get("exif")
            if im.mode not in ("RGB", "L"):
                im = im.convert("RGB")
            if exif_bytes:
                im.save(dst_path, "JPEG", quality=95, optimize=True, exif=exif_bytes)
            else:
                im.save(dst_path, "JPEG", quality=95, optimize=True)
        return

    # Fallback via externe command-line tools indien beschikbaar
    for cmd in (
        ["heif-convert", str(src_path), str(dst_path)],
        ["convert", str(src_path), str(dst_path)],
        ["magick", str(src_path), str(dst_path)],
    ):
        try:
            res = subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            if res.returncode == 0 and dst_path.exists():
                return
        except Exception:
            continue

    raise RuntimeError("Geen HEIC converter beschikbaar (installeer 'pillow-heif': pip install pillow-heif)")

def make_resized_image(src: Path, dst: Path) -> None:
    if not HAS_PIL or not PICTURE_SIZE:
        try:
            safe_copy(src, dst)
        except Exception as e:
            log_bericht(f"    ⚠  Could not copy file: {e}")
        return
    try:
        with safe_image_open(src) as img:
            img = ImageOps.exif_transpose(img)
            img = img.convert("RGB")
            img.thumbnail(PICTURE_SIZE, Image.LANCZOS)
            
            if WATERMARK:
                img = apply_watermark(img, WM_SIZE)
                
            img.save(dst, "JPEG", quality=85, optimize=True)
    except PermissionError as pe:
        log_bericht(f"    ⚠  Access denied (file in use) while creating image for '{src.name}': {pe}")
    except Exception as exc:
        log_bericht(f"    ⚠  Resizing failed for '{src.name}': {exc}")
        try:
            safe_copy(src, dst)
        except Exception:
            pass

def get_exif_data(img_path: Path) -> dict:
    if DISABLE_EXIF or not HAS_PIL:
        return {}
    try:
        with safe_image_open(img_path) as img:
            exif = None
            if hasattr(img, "_getexif"):
                exif = img._getexif()
            if not exif and hasattr(img, "getexif"):
                exif = img.getexif()
            if not exif:
                return {}
            data = {}
            for tag, val in exif.items():
                tag_name = ExifTags.TAGS.get(tag, tag)
                data[tag_name] = val
            return data
    except Exception:
        return {}

def get_formatted_exif(img_path: Path) -> str:
    raw_exif = get_exif_data(img_path)
    if not raw_exif:
        return ""
    
    parts = []
    
    # Camera model
    make = raw_exif.get("Make", "")
    model = raw_exif.get("Model", "")
    if model:
        model_str = str(model).strip()
        make_str = str(make).strip()
        if make_str and make_str.lower() not in model_str.lower():
            parts.append(f"📷 {make_str} {model_str}")
        else:
            parts.append(f"📷 {model_str}")
            
    # Datum / Tijd
    dt_orig = raw_exif.get("DateTimeOriginal")
    if dt_orig:
        try:
            dt = datetime.strptime(str(dt_orig).strip(), "%Y:%m:%d %H:%M:%S")
            parts.append(f"📅 {dt.strftime('%d-%m-%Y %H:%M')}")
        except Exception:
            parts.append(f"📅 {str(dt_orig).strip()}")
            
    return "  •  ".join(parts)

def get_rename_prefix(img_path: Path) -> str:
    """Haalt de EXIF datum-tijd (of mtime) op en returnt YYMMDD_HHMMSS-."""
    exif = get_exif_data(img_path)
    dt_orig = exif.get("DateTimeOriginal")
    if dt_orig:
        try:
            dt = datetime.strptime(str(dt_orig).strip(), "%Y:%m:%d %H:%M:%S")
            return dt.strftime("%y%m%d_%H%M%S-")
        except Exception:
            pass
    try:
        mtime = img_path.stat().st_mtime
        dt = datetime.fromtimestamp(mtime)
        return dt.strftime("%y%m%d_%H%M%S-")
    except Exception:
        return ""

def get_new_filename(img_path: Path) -> str:
    orig_name = img_path.name
    if is_icon_file(orig_name):
        return Path(ICON_FILE_NAME).name
    is_heic = img_path.suffix.lower() in (".heic", ".heif")
    base_name = f"{img_path.stem}.jpg" if is_heic else orig_name
    if not RENAME_FILES:
        return base_name
    if re.match(r"^\d{6}_\d{6}-", orig_name):
        return f"{img_path.stem}.jpg" if is_heic else orig_name
    prefix = get_rename_prefix(img_path)
    return f"{prefix}{base_name}"

